#!/usr/bin/env python3
"""Generate GazaTable.java from data/gaza_prayer_times_year.csv (official Gaza times, UTC+2)."""
import csv, sys
src, dst = sys.argv[1], sys.argv[2]
rows = []
with open(src, encoding="utf-8-sig") as f:
    for r in csv.DictReader(l for l in f if not l.startswith("#")):
        m, d = map(int, r["day"].split("-"))
        mins = []
        for k in ("fajr", "sunrise", "dhuhr", "asr", "maghrib", "isha"):
            h, mm = map(int, r[k].split(":"))
            mins.append(h * 60 + mm)
        rows.append((m, d, mins))
assert len(rows) == 365, len(rows)
lines = ",\n".join("            {%d, %d, %s}" % (m, d, ", ".join(map(str, t))) for m, d, t in rows)
open(dst, "w", encoding="utf-8").write(f"""package ps.gaza.prayer;

// GENERATED by tools/gen_table.py from data/gaza_prayer_times_year.csv -- do not edit.
/** Official Gaza Strip prayer times, minutes after midnight in standard time (UTC+2). Same every year; no 29 Feb row. */
final class GazaTable {{
    private GazaTable() {{}}

    /** {{month, day, fajr, sunrise, dhuhr, asr, maghrib, isha}} */
    static final short[][] ROWS = {{
{lines}
    }};

    /** Minutes for the six prayers, or null when the table has no row (29 Feb). */
    static short[] lookup(int month, int day) {{
        for (short[] r : ROWS) {{
            if (r[0] == month && r[1] == day) {{
                return new short[]{{r[2], r[3], r[4], r[5], r[6], r[7]}};
            }}
        }}
        return null;
    }}
}}
""")
print("wrote", dst, len(rows), "rows")
